-- ===========================================================================
-- 3. entity_metadata + satellites   (migrations 045, 046, 047, 050, 067)
-- ===========================================================================
--
-- Again the FINAL shape. migration_045 created this with a provenance_history
-- JSONB column that migration_047 dropped in favour of entity_provenance_log;
-- 046 added the three per-field timestamps; 050 added updated_by; 067 replaced
-- the provenance CHECK value set.

CREATE TABLE IF NOT EXISTS entity_metadata (
  id                    uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  principal_object_id   uuid        NOT NULL UNIQUE
                                      REFERENCES principal_object(id) ON DELETE CASCADE,
  importance            text,
  relevance             text,
  provenance            text,
  -- COLUMN ORDER IS PART OF THE CONTRACT HERE, not a matter of taste.
  -- migration_045 created this table ending at updated_at; 046 and 050 then
  -- appended importance_updated_at .. updated_by. A migrated database
  -- therefore has created_at/updated_at BEFORE them, and a repaired one used
  -- to have them after -- so `pg_dump -s` of the two disagreed and any
  -- positional INSERT would have gone to different columns. Same reason for
  -- stamp_member below. (Found by scripts/verify-rebuild.ts, Slice #31.01.)
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  importance_updated_at timestamptz,
  relevance_updated_at  timestamptz,
  provenance_updated_at timestamptz,
  updated_by            text
);

-- Covers a pre-046 / pre-050 entity_metadata that already existed.
ALTER TABLE entity_metadata
  ADD COLUMN IF NOT EXISTS importance_updated_at timestamptz,
  ADD COLUMN IF NOT EXISTS relevance_updated_at  timestamptz,
  ADD COLUMN IF NOT EXISTS provenance_updated_at timestamptz,
  ADD COLUMN IF NOT EXISTS updated_by            text;

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger
    WHERE tgname = 'touch_updated_at_entity_metadata'
      AND tgrelid = 'entity_metadata'::regclass
  ) THEN
    CREATE TRIGGER touch_updated_at_entity_metadata
      BEFORE UPDATE ON entity_metadata
      FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
  END IF;
END $$;

-- CHECK constraints. importance / relevance are added only if absent.
DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'chk_em_importance' AND conrelid = 'entity_metadata'::regclass
  ) THEN
    ALTER TABLE entity_metadata
      ADD CONSTRAINT chk_em_importance CHECK (importance IN ('LOW', 'MEDIUM', 'HIGH'));
  END IF;
END $$;

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'chk_em_relevance' AND conrelid = 'entity_metadata'::regclass
  ) THEN
    ALTER TABLE entity_metadata
      ADD CONSTRAINT chk_em_relevance
        CHECK (relevance IN ('INACTIVE', 'HISTORICAL', 'CURRENT', 'FUTURE'));
  END IF;
END $$;

-- provenance: only add the CHECK when no rows would violate it. A database
-- still holding pre-067 values (IMAGE_UPLOAD / TEXT_FILE / EXTERNAL_IMPORT)
-- needs migration_067 to run the remap first -- adding the constraint here
-- would fail the whole script. We warn instead of failing.
DO $$
DECLARE
  stale integer;
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'chk_em_provenance' AND conrelid = 'entity_metadata'::regclass
  ) THEN
    RAISE NOTICE 'chk_em_provenance already present -- left untouched.';
    RETURN;
  END IF;

  SELECT count(*) INTO stale
    FROM entity_metadata
   WHERE provenance IS NOT NULL
     AND provenance NOT IN ('MANUAL', 'IMAGE', 'DOC_FILE', 'COORDINATE_FILE',
                            'ALGORITHM', 'AI_INTERPRETED', 'EXTERNAL_FEED');

  IF stale > 0 THEN
    RAISE WARNING 'chk_em_provenance NOT added: % row(s) hold pre-migration_067 '
                  'provenance values. Apply migration_067_provenance_values.sql '
                  '(it remaps them), then re-run this file.', stale;
  ELSE
    ALTER TABLE entity_metadata
      ADD CONSTRAINT chk_em_provenance
        CHECK (provenance IN ('MANUAL', 'IMAGE', 'DOC_FILE', 'COORDINATE_FILE',
                              'ALGORITHM', 'AI_INTERPRETED', 'EXTERNAL_FEED'));
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS entity_metadata_importance_idx ON entity_metadata (importance);
