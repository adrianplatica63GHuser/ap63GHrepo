-- already exists (the groups table depends on it too), but guard anyway --
-- a missing type would abort the whole script.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'group_target_type') THEN
    CREATE TYPE group_target_type AS ENUM
      ('PHYSICAL_PERSON', 'JUDICIAL_PERSON', 'PROPERTY', 'DOCUMENT');
  END IF;
END $$;

