  END IF;

  IF to_regclass('public.entity_metadata') IS NOT NULL
     AND NOT EXISTS (
       SELECT 1 FROM pg_constraint c
        WHERE c.conname  = 'chk_em_relevance'
          AND c.conrelid = to_regclass('public.entity_metadata')
     ) THEN
