    SELECT 1 FROM pg_constraint
    WHERE conname = 'lookup_property_type_key_unique'
      AND conrelid = 'lookup_property_type'::regclass
  ) THEN
    RETURN;
  END IF;

  SELECT count(*) INTO dupes FROM (
    SELECT key FROM lookup_property_type
    WHERE key IS NOT NULL GROUP BY key HAVING count(*) > 1
  ) x;

  IF dupes > 0 THEN
    RAISE WARNING 'lookup_property_type.key UNIQUE not added: % duplicate value(s). '
                  'Apply migration_039_property_type_key.sql, which backfills '
                  'distinct slugs first.', dupes;
  ELSE
    ALTER TABLE lookup_property_type
      ADD CONSTRAINT lookup_property_type_key_unique UNIQUE (key);
  END IF;
END $$;

