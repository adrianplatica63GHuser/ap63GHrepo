-- ===========================================================================
-- supabase_repair_missing_tables.sql   (Slice #21.09.help.error)
--
-- PURPOSE
--   Bring a Supabase (or any) database up to the shape declared in
--   src/db/schema/index.ts, WITHOUT dropping or rewriting anything.
--
-- WHY THIS FILE EXISTS
--   src/db/supabase_schema_full.sql had drifted badly: it declared 37 tables
--   where schema/index.ts declares 49, and 21 of the 37 it did have were
--   missing columns added by later migrations. Any database rebuilt from that
--   file was born broken. This file is the additive repair; the full-rebuild
--   file is now regenerated by scripts/Export-SupabaseSchema.ps1 instead of
--   being hand-maintained.
--
-- SAFETY
--   Every statement is idempotent (IF NOT EXISTS / guarded DO block). Nothing
--   is dropped. Running it against an already-correct database is a no-op that
--   reports "0 missing". Safe to run on production with live data.
--
--   THE STATEMENTS THAT ARE NOT PURELY ADDITIVE ARE LISTED BELOW, EACH BY WHAT
--   IT IS. **There is deliberately no count, and putting one back is the
--   mistake this paragraph now exists to forbid** (Slice #34.18). A total is a
--   second copy of the list, kept by hand, and it is the copy that rots: this
--   file carried one for four slices and it was wrong in three of them. The
--   UNIQUE on `lookup_property_type` was written as "an eighth" while the
--   total said seven; #34.04 moved the total to eleven without ever listing
--   that statement; #34.09 listed it at last, as the twelfth. Not one of those
--   corrections changed what the file DOES - they were renumberings of a
--   number that had no reason to exist. A bullet identified by its own
--   statement cannot be mis-numbered, because it has no number.
--
--   So: to add one, add a bullet. Nothing renumbers and nothing above it
--   changes. What has not changed either is why the list is here - it is the
--   paragraph an operator reads before running this file against production -
--   or the rule that anything added here holds to "additive" unless it says
--   why not, and says so here.
--
--   NOT PURELY ADDITIVE:
--
--     * `UPDATE <t> SET origin = 'MANUAL' WHERE origin IS NULL`, on
--       lookup_document_type, lookup_tarla and lookup_institution (#26.12,
--       extended to the other two by #34.02). It writes data. It touches ONLY
--       rows whose origin is NULL, which the application already reads as
--       MANUAL, so it changes no behaviour - but it is a write, and this file
--       used to promise there were none.
--
--     * `ALTER TABLE <t> ALTER COLUMN origin SET NOT NULL`, on the same three
--       tables (#26.12, #34.02). Each takes ACCESS EXCLUSIVE for the length of
--       a full-table scan. On lookup tables of a few dozen rows that is
--       immeasurable; on a large table it would not be.
--
--     * `ALTER TABLE property ADD CONSTRAINT property_tarla_id_fkey FOREIGN
--       KEY ...` (#34.03). The ADD COLUMN beside it is additive; the
--       constraint is not quite - it takes ACCESS EXCLUSIVE on `property` and
--       validates every existing row, which is the same cost as the SET NOT
--       NULLs above. It validates trivially today because this file can only
--       ever leave `tarla_id` NULL (it has no way to resolve text against
--       lookup rows and must not guess), but on a database where the column is
--       already populated the scan is real.
--
--     * `UPDATE lookup_person_role SET valid_for_property = false WHERE
--       valid_for_property IS NULL`, and the same for `valid_for_person`
--       (#34.04). Writes, of the same category and with the same argument as
--       the `origin` UPDATEs above: they touch only rows holding NULL, which
--       the application already reads as false.
--
--     * `ALTER TABLE lookup_person_role ALTER COLUMN valid_for_property SET
--       NOT NULL`, and the same for `valid_for_person` (#34.04). More ACCESS
--       EXCLUSIVE full-table scans, on a table of a few dozen roles, so
--       immeasurable here - listed because the list is what an operator reads,
--       not because the cost is real.
--
--       The lookup_person_role statements above exist because `ADD COLUMN IF
--       NOT EXISTS` is a complete no-op over a column of the same name that is
--       nullable with no default; the block in section 8 says so at length.
--
--     * `ALTER TABLE lookup_property_type ADD CONSTRAINT
--       lookup_property_type_key_unique UNIQUE (key)`, in section 8. It has
--       been in this file since before #26.12 and went unlisted until #34.09,
--       which is the debt the numbering above kept failing to settle. It takes
--       ACCESS EXCLUSIVE while it builds its index. Its own block already
--       refuses on duplicate data with a WARNING rather than failing, which is
--       the shape the bullet below copies.
--
--     * `ALTER TABLE entity_metadata ADD CONSTRAINT chk_em_importance CHECK
--       (importance IN (...))`, and the same shape for `chk_em_relevance` and
--       `chk_em_provenance`. Each takes ACCESS EXCLUSIVE and validates every
--       existing row - the same cost, and therefore the same reason to be
--       here, as the FK and the SET NOT NULLs above. **All three now COUNT
--       FIRST** and RAISE a WARNING rather than attempting the ADD (#34.31
--       for importance and relevance; provenance has done so since #26.12).
--       The importance and relevance messages carry the count AND a query
--       that lists the offending rows; provenance's carries the count and
--       names migration_067, which is the file that remaps them. Until that slice the importance and relevance CHECKs had
--       no such guard, so on a database holding a drifted value they simply
--       failed - and this file runs under `psql -f` with no ON_ERROR_STOP, so
--       that failure scrolled past a post-flight still reporting OK. ⚠️ **A
--       WARNING here means the constraint is NOT on the table**, which is why
--       section 10 now asks about ALL THREE by name - provenance included,
--       which had warned without an answer at the end since #26.12: a guard
--       that turns a failure into a skip has moved the problem rather than
--       solved it unless something downstream says the skip happened.
--
--     * the `chk_ldt_origin`, `chk_lt_origin` and `chk_li_origin` constraints
--       on lookup_document_type, lookup_tarla and lookup_institution (#26.12,
--       #34.02) - each one an ADD CONSTRAINT over the origin column. ACCESS
--       EXCLUSIVE and a full validation each. These DO count first and RAISE a
--       WARNING rather than failing. (Described rather than quoted, because
--       document-type-origin-single-source.test.ts records as measured fact
--       that no comment in either SQL file spells out that constraint's
--       expression - the suite strips comments before it scans, so it stays
--       green either way, but the measurement should stay true.)
--
--       ⚠️ **These six CHECKs were missing from this list under every version
--       of the running total**, which is the point the numbering scheme was
--       never going to reach: the failure was OMISSION, not mis-numbering, and
--       a bullet list does not fix omission by itself. What it does is remove
--       the reason not to add one - there is nothing to renumber, so adding
--       the bullet you noticed costs nothing and disturbs nothing. (#34.18
--       adversarial review found all six.)
--
--     * `CREATE UNIQUE INDEX IF NOT EXISTS` on
--       stamp_member_stamp_principal_object_unique, entity_tag_entity_tag_unique
--       and property_corner_source_document_unique. Each follows a
--       `CREATE TABLE IF NOT EXISTS`, so on a project that already HAS the
--       table with colliding rows the index build fails on existing data -
--       exactly the hazard spelled out for the unique index below. **All three
--       now COUNT FIRST** and RAISE a WARNING giving the number of colliding
--       groups and a query that lists them, rather than attempting the CREATE
--       (#34.31), and section 10 asks about
--       each of them by name afterwards for the reason given in the bullet
--       above.
--
--     * `ALTER TABLE <t> ALTER COLUMN <c> SET DEFAULT ...`, on
--       lookup_person_role.valid_for_property and .valid_for_person and on the
--       three `origin` columns. Catalogue-only, so no scan and no rewrite -
--       listed because they sit BETWEEN the UPDATE and the SET NOT NULL of
--       each convergence above, and a list that skipped the middle statement
--       of a three-step sequence would read as though the sequence were two.
--
--     * `CREATE UNIQUE INDEX lookup_document_type_name_normalised_unique`
--       (migration_080, #34.09). It is not additive in the way the ADD COLUMNs
--       are: it takes SHARE on lookup_document_type for the length of the
--       build -- readers unaffected, writers blocked -- and IT COULD FAIL ON
--       EXISTING DATA, which is why it counts first. (It used to say "together
--       with the bullet above" and point at the three unguarded unique indexes;
--       #34.31 guarded those, so this one is no longer one of a pair.) Two types whose names
--       differ only by diacritics, case or punctuation are one name to the
--       index. The block in section 8 therefore counts first and RAISEs a
--       WARNING naming migration_080 rather than attempting the CREATE,
--       because this file runs under `psql -f` with no ON_ERROR_STOP and a
--       bare failure would scroll past a post-flight still reporting OK.
--
--     * `CREATE UNIQUE INDEX lookup_tarla_indicativ_folded_unique`
--       (migration_083, #34.32). The bullet above, one table over, and every
--       word of its hazard applies: SHARE on lookup_tarla for the length of
--       the build, and IT COULD FAIL ON EXISTING DATA, so its block counts
--       first and RAISEs a WARNING naming migration_083. What differs is the
--       FOLD. This one is `pg_temp.ga40_fold` - NFD-decompose, strip the
--       combining marks, lowercase, collapse whitespace, trim - and NOT
--       `ga40_norm_name`, which additionally drops everything outside
--       [a-z0-9]. A tarla code is `47/2`; stripping the separator would make
--       it one code with `472`. Two adjacent unique indexes, two different
--       folds, deliberately - do not "harmonise" the two blocks in section 8.
--
-- HOW TO APPLY
--   Supabase : paste this whole file into the SQL Editor and run.
--   Local    : docker cp src/db/supabase_repair_missing_tables.sql ga40prj-postgres:/tmp/repair.sql
--              docker exec ga40prj-postgres psql -U postgres -d ga40db -f /tmp/repair.sql
--
-- PREREQUISITES (all created by earlier migrations; assumed present)
--   - function touch_updated_at()
--   - enum group_target_type
--   - tables principal_object, person, property, document, groups
--   - table lookup_tarla (Slice #34.03's block in section 8 references it, and
--     an adversarial round pointed out it was assumed rather than stated)
--   - table lookup_person_role (Slice #34.04's block in section 8 adds two
--     columns to it; it is created by migration_013 and this file never has)
--   - tables lookup_person_type and lookup_institution, referenced by the FKs
--     in section 8's `natural_person` and `document` ALTERs. Neither is an
--     ALTER TARGET, so neither shows up in a sweep of statement heads - and
--     because each sits in a MULTI-CLAUSE `ALTER TABLE`, its absence takes the
--     unrelated columns beside it down too: no lookup_person_type means
--     natural_person gets neither physical_person_type_id NOR
--     correspondence_same_as_home. lookup_institution's absence at least ends
--     POST-FLIGHT FAILED; lookup_person_type's ends OK. (#34.31 round 5.)
--   - tables natural_person, person_version, property_version,
--     document_version, property_address, property_corner. Each is an ALTER
--     target in section 8 and none was ever stated here; on a database
--     lacking one, that ALTER raises and the run still ends POST-FLIGHT OK.
--     Listed now because the list is free; the silent-failure half is in the
--     #34.31 handover under "Noticed, not fixed".
--   - table lookup_property_type (section 8 has added four columns to it and
--     a UNIQUE to its `key` since long before this list existed, and never
--     said so; #34.31 found the ALTER raising 42P01 on a database without it)
--   - table lookup_document_type (Slice #34.09's block in section 8 puts a
--     unique index on it; it is created by migration_002 and this file never
--     has -- and section 8 has been adding its `origin` column since #26.12
--     without ever saying so here)
--   - table lookup_tarla, again (Slice #34.32's block in section 8 puts a
--     unique index on it, which is a second reason beyond #34.03's reference
--     above; this file never creates it, and neither does any migration in
--     `src/db/migration_*.sql` -- it predates the numbered chain)
--
-- Read the NOTICE output at the end. It reports anything still missing.
-- ===========================================================================


-- ===========================================================================
-- 0. PRE-FLIGHT -- report what is missing before we change anything
-- ===========================================================================

DO $$
DECLARE
  expected text[] := ARRAY[
    'help_content', 'help_hint',
    'stamps', 'stamp_member',
    'entity_metadata', 'entity_provenance_log', 'entity_metadata_version',
    'entity_cross_reference', 'entity_tag',
    'calculation_run', 'calculation_run_output',
    'time_frame_setting',
    'property_corner_source'
  ];
  t       text;
  missing text[] := '{}';
  stale   integer;
BEGIN
  FOREACH t IN ARRAY expected LOOP
    IF NOT EXISTS (
      SELECT 1 FROM information_schema.tables
      WHERE table_schema = 'public' AND table_name = t
    ) THEN
      missing := array_append(missing, t);
    END IF;
  END LOOP;

  IF array_length(missing, 1) IS NULL THEN
    RAISE NOTICE 'PRE-FLIGHT: all 13 tables already present. This run will be a no-op.';
  ELSE
    RAISE NOTICE 'PRE-FLIGHT: % table(s) missing and about to be created: %',
      array_length(missing, 1), array_to_string(missing, ', ');
  END IF;

  -- ── Slice #29.04: is this database on the right side of migration_070? ──
  --
  -- This file repairs a database towards the shape in src/db/schema/index.ts,
  -- and that shape no longer has deleted_at. Creating the thirteen tables in
  -- their CURRENT shape on a database whose person / groups / lookups still
  -- carry the column produces something that matches neither the old schema
  -- nor the new one, and nothing afterwards would say so.
  --
  -- Scoped to the sixteen tables migration_070 owns, on purpose. An earlier
  -- version counted every deleted_at column in `public` and so refused to run
  -- on a correctly-migrated database that happened to have an unrelated audit
  -- table — asserting, in the error text, something plainly false.
  SELECT count(*)::int INTO stale
    FROM information_schema.columns
   WHERE table_schema = 'public'
     AND column_name  = 'deleted_at'
     AND table_name IN (
       'person', 'property', 'document',
       'lookup_property_type', 'lookup_tarla', 'lookup_use_category',
       'lookup_person_type', 'lookup_person_role',
       'lookup_judicial_person_type', 'lookup_citizenship',
       'lookup_document_type', 'lookup_institution',
       'lookup_property_property_role', 'lookup_document_document_role',
       'groups', 'stamps');

  IF stale > 0 THEN
    RAISE EXCEPTION 'PRE-FLIGHT: % of this app''s tables still carry deleted_at, so this database predates migration_070 (Slice #29.04). Apply the migrations first - this file brings a database up to the CURRENT schema and will not drop columns behind your back. Nothing has been changed.', stale;
  END IF;
END $$;


