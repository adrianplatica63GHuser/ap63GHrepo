    SELECT 1
      FROM pg_index i
     WHERE i.indrelid    = 'lookup_document_type'::regclass
       AND i.indisunique
       AND i.indisvalid
       AND i.indpred IS NOT NULL
       AND i.indnkeyatts = 1
       AND i.indkey[0]   = 0
  ) THEN
    RETURN;
  END IF;

  SELECT count(*) INTO dupes FROM (
    SELECT regexp_replace(
             btrim(regexp_replace(
               regexp_replace(
                 lower(normalize(coalesce(name, ''), NFD)),
                 '[' || chr(768) || '-' || chr(879) || ']', '', 'g'),
               '\s+', ' ', 'g')),
