      ADD CONSTRAINT chk_em_relevance
        CHECK (relevance IN ('INACTIVE', 'HISTORICAL', 'CURRENT', 'FUTURE'));
  END IF;
END $$;

-- provenance: only add the CHECK when no rows would violate it. A database
-- still holding pre-067 values (IMAGE_UPLOAD / TEXT_FILE / EXTERNAL_IMPORT)
-- needs migration_067 to run the remap first -- adding the constraint here
-- would fail the whole script. We warn instead of failing.
DO $$
DECLARE
  stale integer;
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'chk_em_provenance' AND conrelid = 'entity_metadata'::regclass
  ) THEN
    RAISE NOTICE 'chk_em_provenance already present -- left untouched.';
    RETURN;
  END IF;

  SELECT count(*) INTO stale
    FROM entity_metadata
   WHERE provenance IS NOT NULL
     AND provenance NOT IN ('MANUAL', 'IMAGE', 'DOC_FILE', 'COORDINATE_FILE',
                            'ALGORITHM', 'AI_INTERPRETED', 'EXTERNAL_FEED');

  IF stale > 0 THEN
    RAISE WARNING 'chk_em_provenance NOT added: % row(s) hold pre-migration_067 '
                  'provenance values. Apply migration_067_provenance_values.sql '
                  '(it remaps them), then re-run this file.', stale;
  ELSE
    ALTER TABLE entity_metadata
      ADD CONSTRAINT chk_em_provenance
        CHECK (provenance IN ('MANUAL', 'IMAGE', 'DOC_FILE', 'COORDINATE_FILE',
                              'ALGORITHM', 'AI_INTERPRETED', 'EXTERNAL_FEED'));
  END IF;
END $$;

