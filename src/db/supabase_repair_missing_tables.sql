  END IF;

  IF to_regclass('public.stamp_member') IS NOT NULL
     AND NOT EXISTS (
       SELECT 1 FROM pg_index i
        WHERE i.indexrelid = to_regclass('public.stamp_member_stamp_principal_object_unique')
